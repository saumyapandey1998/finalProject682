def make_loaders(data_dir, batch_size=16, use_train_split_for_validation=True):
    train_dir = os.path.join(data_dir, "train")
    val_dir = os.path.join(data_dir, "val")
    test_dir = os.path.join(data_dir, "test")

    train_full_aug = datasets.ImageFolder(train_dir, transform=train_transforms)
    train_full_plain = datasets.ImageFolder(train_dir, transform=val_test_transforms)
    class_names = train_full_aug.classes

    if use_train_split_for_validation:
        val_size = int(0.15 * len(train_full_aug))
        train_size = len(train_full_aug) - val_size

        generator = torch.Generator().manual_seed(SEED)
        all_indices = torch.randperm(len(train_full_aug), generator=generator).tolist()
        train_indices = all_indices[:train_size]
        val_indices = all_indices[train_size:]

        train_dataset = Subset(train_full_aug, train_indices)
        val_dataset = Subset(train_full_plain, val_indices)

        train_targets_for_weights = np.array([train_full_aug.targets[i] for i in train_indices])
    else:
        train_dataset = train_full_aug
        val_dataset = datasets.ImageFolder(val_dir, transform=val_test_transforms)
        train_targets_for_weights = np.array(train_full_aug.targets)

    test_dataset = datasets.ImageFolder(test_dir, transform=val_test_transforms)

    train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True, num_workers=NUM_WORKERS, pin_memory=True)
    val_loader = DataLoader(val_dataset, batch_size=batch_size, shuffle=False, num_workers=NUM_WORKERS, pin_memory=True)
    test_loader = DataLoader(test_dataset, batch_size=batch_size, shuffle=False, num_workers=NUM_WORKERS, pin_memory=True)

    num_classes = len(class_names)
    class_counts = np.bincount(train_targets_for_weights, minlength=num_classes)
    class_counts_safe = np.where(class_counts == 0, 1, class_counts)

    class_weights = 1.0 / torch.tensor(class_counts_safe, dtype=torch.float)
    class_weights = class_weights / class_weights.sum()
    class_weights = class_weights.to(device)

    class_to_idx = datasets.ImageFolder(train_dir).class_to_idx

    print("\nLoaded:", data_dir)
    print("Classes:", class_names)
    print("Class to index:", class_to_idx)
    print("Class counts used for weights:", dict(zip(class_names, class_counts)))
    print("Class weights:", class_weights)
    print("Train size:", len(train_dataset))
    print("Val size:", len(val_dataset))
    print("Test size:", len(test_dataset))

    return {
        "train_loader": train_loader,
        "val_loader": val_loader,
        "test_loader": test_loader,
        "train_dataset": train_dataset,
        "val_dataset": val_dataset,
        "test_dataset": test_dataset,
        "class_names": class_names,
        "class_weights": class_weights,
        "num_classes": num_classes,
        "class_to_idx": class_to_idx,
    }

#Medical Attention Localization Module

class MedicalAttentionLocalizationModule(nn.Module):
    """
    This is the new contribution.

    DINOv3 gives patch tokens.
    This module learns which patch tokens are medically important.
    It also adds a soft lung-shaped prior so attention is encouraged toward lung regions.
    """

    def __init__(self, hidden_dim, prior_strength=1.0):
        super().__init__()
        self.prior_strength = prior_strength

        self.attention_mlp = nn.Sequential(
            nn.LayerNorm(hidden_dim),
            nn.Linear(hidden_dim, hidden_dim // 2),
            nn.GELU(),
            nn.Linear(hidden_dim // 2, 1),
        )

    def build_lung_prior(self, grid_h, grid_w, device):
        y = torch.linspace(-1.0, 1.0, grid_h, device=device)
        x = torch.linspace(-1.0, 1.0, grid_w, device=device)
        yy, xx = torch.meshgrid(y, x, indexing="ij")

        left_lung = (((xx + 0.35) / 0.38) ** 2 + ((yy + 0.02) / 0.78) ** 2) <= 1.0
        right_lung = (((xx - 0.35) / 0.38) ** 2 + ((yy + 0.02) / 0.78) ** 2) <= 1.0
        lung_mask = (left_lung | right_lung).float()

        lung_mask = lung_mask + 0.15
        lung_mask = lung_mask / lung_mask.max()
        return lung_mask.reshape(1, grid_h * grid_w, 1)

    def forward(self, patch_tokens):
        batch_size, num_patches, hidden_dim = patch_tokens.shape

        grid_size = int(math.sqrt(num_patches))
        if grid_size * grid_size != num_patches:
            learned_logits = self.attention_mlp(patch_tokens)
            attention_weights = torch.softmax(learned_logits, dim=1)
            localized_embedding = torch.sum(attention_weights * patch_tokens, dim=1)
            return localized_embedding, attention_weights.squeeze(-1), None

        learned_logits = self.attention_mlp(patch_tokens)
        lung_prior = self.build_lung_prior(grid_size, grid_size, patch_tokens.device)

        attention_logits = learned_logits + self.prior_strength * lung_prior
        attention_weights = torch.softmax(attention_logits, dim=1)

        localized_embedding = torch.sum(attention_weights * patch_tokens, dim=1)
        attention_map = attention_weights.reshape(batch_size, grid_size, grid_size)

        return localized_embedding, attention_weights.squeeze(-1), attention_map

#DINO classifier with custom medical attention module

class DINOv3MedicalAttentionClassifier(nn.Module):
    def __init__(self, model_name, num_classes, dropout=0.3, prior_strength=1.0):
        super().__init__()

        self.backbone = AutoModel.from_pretrained(model_name)
        hidden_dim = self.backbone.config.hidden_size

        self.medical_attention = MedicalAttentionLocalizationModule(
            hidden_dim=hidden_dim,
            prior_strength=prior_strength
        )

        self.classifier = nn.Sequential(
            nn.LayerNorm(hidden_dim * 2),
            nn.Linear(hidden_dim * 2, 512),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(512, num_classes)
        )

    def forward(self, pixel_values, return_attention=False):
        outputs = self.backbone(pixel_values=pixel_values)
        tokens = outputs.last_hidden_state

        cls_token = tokens[:, 0, :]
        patch_tokens = tokens[:, 1:, :]

        localized_embedding, attention_weights, attention_map = self.medical_attention(patch_tokens)
        fused_embedding = torch.cat([cls_token, localized_embedding], dim=1)
        logits = self.classifier(fused_embedding)

        if return_attention:
            return logits, attention_map, attention_weights
        return logits

#Training helpers

def freeze_backbone(model):
    for param in model.backbone.parameters():
        param.requires_grad = False


def unfreeze_backbone(model):
    for param in model.backbone.parameters():
        param.requires_grad = True


def train_one_epoch(model, loader, criterion, optimizer, device):
    model.train()
    running_loss = 0.0
    all_preds = []
    all_labels = []

    for images, labels in loader:
        images = images.to(device, non_blocking=True)
        labels = labels.to(device, non_blocking=True)

        optimizer.zero_grad()
        logits = model(images)
        loss = criterion(logits, labels)
        loss.backward()
        optimizer.step()

        running_loss += loss.item() * images.size(0)
        preds = torch.argmax(logits, dim=1)
        all_preds.extend(preds.detach().cpu().numpy())
        all_labels.extend(labels.detach().cpu().numpy())

    epoch_loss = running_loss / len(loader.dataset)
    epoch_acc = accuracy_score(all_labels, all_preds)
    return epoch_loss, epoch_acc


def evaluate(model, loader, criterion, device, threshold=None, positive_class_idx=1):
    model.eval()
    running_loss = 0.0
    all_preds = []
    all_labels = []
    all_probs = []

    with torch.no_grad():
        for images, labels in loader:
            images = images.to(device, non_blocking=True)
            labels = labels.to(device, non_blocking=True)

            logits = model(images)
            loss = criterion(logits, labels)
            probs = torch.softmax(logits, dim=1)

            if threshold is not None:
                positive_probs = probs[:, positive_class_idx]
                preds = (positive_probs >= threshold).long()
            else:
                preds = torch.argmax(probs, dim=1)

            running_loss += loss.item() * images.size(0)
            all_preds.extend(preds.detach().cpu().numpy())
            all_labels.extend(labels.detach().cpu().numpy())
            all_probs.extend(probs.detach().cpu().numpy())

    epoch_loss = running_loss / len(loader.dataset)
    epoch_acc = accuracy_score(all_labels, all_preds)
    return epoch_loss, epoch_acc, np.array(all_labels), np.array(all_preds), np.array(all_probs)


def train_model_phase(model, loaders, optimizer, phase_name, best_path, epochs=5, patience=3):
    # Small label smoothing reduces overconfidence and can reduce false pneumonia predictions.
    criterion = nn.CrossEntropyLoss(weight=loaders["class_weights"], label_smoothing=0.05)
    best_val_loss = float("inf")
    patience_counter = 0
    history = []

    for epoch in range(1, epochs + 1):
        train_loss, train_acc = train_one_epoch(
            model, loaders["train_loader"], criterion, optimizer, device
        )
        val_loss, val_acc, _, _, _ = evaluate(
            model, loaders["val_loader"], criterion, device
        )

        history.append({
            "epoch": epoch,
            "train_loss": train_loss,
            "train_acc": train_acc,
            "val_loss": val_loss,
            "val_acc": val_acc,
        })

        print(
            f"{phase_name} | Epoch {epoch}/{epochs} | "
            f"Train Loss: {train_loss:.4f} | Train Acc: {train_acc:.4f} | "
            f"Val Loss: {val_loss:.4f} | Val Acc: {val_acc:.4f}"
        )

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            patience_counter = 0
            torch.save(model.state_dict(), best_path)
            print("Saved best model:", best_path)
        else:
            patience_counter += 1
            if patience_counter >= patience:
                print("Early stopping.")
                break

    model.load_state_dict(torch.load(best_path, map_location=device))
    return history


def train_staged_dinov3(loaders, model_name, frozen_epochs=5, finetune_epochs=5):
    model = DINOv3MedicalAttentionClassifier(
        model_name=DINO_MODEL_NAME,
        num_classes=loaders["num_classes"],
        dropout=0.4,
        prior_strength=0.5
    ).to(device)

    frozen_path = f"{model_name}_dino_attention_frozen_best.pth"
    finetune_path = f"{model_name}_dino_attention_finetuned_best.pth"

    print("Phase 1: Frozen DINO backbone. Training classifier + medical attention only.")
    freeze_backbone(model)
    optimizer = optim.AdamW(
        list(model.medical_attention.parameters()) + list(model.classifier.parameters()),
        lr=1e-4,
        weight_decay=1e-4
    )
    history_1 = train_model_phase(
        model, loaders, optimizer,
        phase_name=f"{model_name} Frozen",
        best_path=frozen_path,
        epochs=frozen_epochs,
        patience=3
    )

    print("Phase 2: Fine-tuning full model with small learning rate.")
    unfreeze_backbone(model)
    optimizer = optim.AdamW([
        {"params": model.backbone.parameters(), "lr": 5e-7},
        {"params": model.medical_attention.parameters(), "lr": 3e-5},
        {"params": model.classifier.parameters(), "lr": 3e-5},
    ], weight_decay=1e-4)

    history_2 = train_model_phase(
        model, loaders, optimizer,
        phase_name=f"{model_name} Finetune",
        best_path=finetune_path,
        epochs=finetune_epochs,
        patience=3
    )

    return model, frozen_path, finetune_path, history_1, history_2


def evaluate_and_print(model, loaders, title, threshold=None, positive_class_idx=1):
    criterion = nn.CrossEntropyLoss(weight=loaders["class_weights"])
    test_loss, test_acc, y_true, y_pred, y_probs = evaluate(
        model,
        loaders["test_loader"],
        criterion,
        device,
        threshold=threshold,
        positive_class_idx=positive_class_idx
    )

    print("\n" + "=" * 60)
    print(title)
    print("=" * 60)
    print("Test Loss:", round(test_loss, 4))
    print("Test Accuracy:", round(test_acc, 4))
    print("Balanced Accuracy:", round(balanced_accuracy_score(y_true, y_pred), 4))
    print("Precision:", round(precision_score(y_true, y_pred, average="weighted", zero_division=0), 4))
    print("Recall:", round(recall_score(y_true, y_pred, average="weighted", zero_division=0), 4))
    print("F1:", round(f1_score(y_true, y_pred, average="weighted", zero_division=0), 4))
    print("Classification Report:")
    print(classification_report(y_true, y_pred, target_names=loaders["class_names"], zero_division=0))
    print("Confusion Matrix:", confusion_matrix(y_true, y_pred))

    return y_true, y_pred, y_probs


def tune_binary_threshold(model, loaders, thresholds=None, positive_class_name="PNEUMONIA", split="val_loader"):
    if thresholds is None:
        thresholds = [0.50, 0.55, 0.60, 0.65, 0.70, 0.75, 0.80, 0.85]

    criterion = nn.CrossEntropyLoss(weight=loaders["class_weights"])
    positive_class_idx = loaders["class_to_idx"][positive_class_name]
    normal_idx = loaders["class_to_idx"].get("NORMAL", 0)

    rows = []
    for threshold in thresholds:
        loss, acc, y_true, y_pred, y_probs = evaluate(
            model,
            loaders[split],
            criterion,
            device,
            threshold=threshold,
            positive_class_idx=positive_class_idx
        )

        rows.append({
            "threshold": threshold,
            "loss": loss,
            "accuracy": accuracy_score(y_true, y_pred),
            "balanced_accuracy": balanced_accuracy_score(y_true, y_pred),
            "macro_f1": f1_score(y_true, y_pred, average="macro", zero_division=0),
            "weighted_f1": f1_score(y_true, y_pred, average="weighted", zero_division=0),
            "normal_recall": recall_score(y_true, y_pred, labels=[normal_idx], average="macro", zero_division=0),
            "pneumonia_recall": recall_score(y_true, y_pred, labels=[positive_class_idx], average="macro", zero_division=0),
        })

    threshold_df = pd.DataFrame(rows)
    print("\nStage 1 threshold tuning results on", split)
    print(threshold_df)

    best_row = threshold_df.sort_values("macro_f1", ascending=False).iloc[0]
    best_threshold = float(best_row["threshold"])
    print("Best Stage 1 threshold by macro F1:", best_threshold)

    return best_threshold, threshold_df

