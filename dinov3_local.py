def two_stage_predict(image_tensor, pneumonia_threshold=0.50):
    stage1_net.eval()
    stage2_net.eval()

    image_tensor = image_tensor.to(device)

    with torch.no_grad():
        stage1_logits = stage1_net(image_tensor)
        stage1_probs = torch.softmax(stage1_logits, dim=1)[0]

        pneumonia_idx = binary_loaders["class_to_idx"]["PNEUMONIA"]
        pneumonia_prob = stage1_probs[pneumonia_idx].item()

        if pneumonia_prob < pneumonia_threshold:
            return "NORMAL", pneumonia_prob, None

        stage2_logits = stage2_net(image_tensor)
        stage2_probs = torch.softmax(stage2_logits, dim=1)[0]
        stage2_pred_idx = torch.argmax(stage2_probs).item()
        subtype_name = subtype_idx_to_class[stage2_pred_idx]
        subtype_prob = stage2_probs[stage2_pred_idx].item()

        return subtype_name, pneumonia_prob, subtype_prob


