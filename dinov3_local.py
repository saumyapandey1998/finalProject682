inv_mean = np.array(image_mean)
inv_std = np.array(image_std)


def denormalize_image(tensor_img):
    img = tensor_img.detach().cpu().numpy().transpose(1, 2, 0)
    img = img * inv_std + inv_mean
    img = np.clip(img, 0, 1)
    return img


def overlay_attention(original_img, attention_map, alpha=0.45):
    heatmap = attention_map.detach().cpu().numpy()
    heatmap = cv2.resize(heatmap, (original_img.shape[1], original_img.shape[0]))
    heatmap = (heatmap - heatmap.min()) / (heatmap.max() - heatmap.min() + 1e-8)
    heatmap_uint8 = np.uint8(255 * heatmap)
    heatmap_color = cv2.applyColorMap(heatmap_uint8, cv2.COLORMAP_JET)
    heatmap_color = cv2.cvtColor(heatmap_color, cv2.COLOR_BGR2RGB) / 255.0
    overlay = (1 - alpha) * original_img + alpha * heatmap_color
    overlay = np.clip(overlay, 0, 1)
    return overlay, heatmap


