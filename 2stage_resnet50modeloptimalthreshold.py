# Dataset Creation

def safe_copy(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy2(src, dst)


def is_image_file(file_name):
    valid_extensions = (".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff", ".webp")
    return file_name.lower().endswith(valid_extensions)


def create_two_stage_datasets(original_dir, binary_dir, subtype_dir, three_class_dir):
    """
    Creates:
    1. binary_dir: NORMAL vs PNEUMONIA
    2. subtype_dir: BACTERIAL vs VIRAL
    3. three_class_dir: NORMAL vs BACTERIAL vs VIRAL
    """

    if os.path.exists(binary_dir) and os.path.exists(subtype_dir) and os.path.exists(three_class_dir):
        print("Datasets already exist. Skipping dataset creation.")
        return

    for split in ["train", "val", "test"]:
        original_split_dir = os.path.join(original_dir, split)
        normal_dir = os.path.join(original_split_dir, "NORMAL")
        pneumonia_dir = os.path.join(original_split_dir, "PNEUMONIA")

        for base_dir, classes in [
            (binary_dir, ["NORMAL", "PNEUMONIA"]),
            (subtype_dir, ["BACTERIAL", "VIRAL"]),
            (three_class_dir, ["NORMAL", "BACTERIAL", "VIRAL"]),
        ]:
            for cls in classes:
                os.makedirs(os.path.join(base_dir, split, cls), exist_ok=True)

        # NORMAL images
        if os.path.exists(normal_dir):
            for file_name in os.listdir(normal_dir):
                if not is_image_file(file_name):
                    continue

                src = os.path.join(normal_dir, file_name)
                if not os.path.isfile(src):
                    continue

                safe_copy(src, os.path.join(binary_dir, split, "NORMAL", file_name))
                safe_copy(src, os.path.join(three_class_dir, split, "NORMAL", file_name))

        # PNEUMONIA images
        if os.path.exists(pneumonia_dir):
            for file_name in os.listdir(pneumonia_dir):
                if not is_image_file(file_name):
                    continue

                src = os.path.join(pneumonia_dir, file_name)
                if not os.path.isfile(src):
                    continue

                lower_name = file_name.lower()

                safe_copy(src, os.path.join(binary_dir, split, "PNEUMONIA", file_name))

                if "bacteria" in lower_name:
                    safe_copy(src, os.path.join(subtype_dir, split, "BACTERIAL", file_name))
                    safe_copy(src, os.path.join(three_class_dir, split, "BACTERIAL", file_name))

                elif "virus" in lower_name:
                    safe_copy(src, os.path.join(subtype_dir, split, "VIRAL", file_name))
                    safe_copy(src, os.path.join(three_class_dir, split, "VIRAL", file_name))

                else:
                    print("Skipped unknown pneumonia subtype:", file_name)

    print("Created all datasets.")


